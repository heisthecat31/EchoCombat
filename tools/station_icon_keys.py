"""plugin/station_icon_keys.h: the equipment station's grid icon keys, for VeilNet.dll.

The station canvas (72e4349798ae3ea1, as gear_icons.py leaves it) ends in an index of its
elements: 24-byte records (key, slot, element name), the record count at +1A0h. Each grid
cell (slot <type>_icon_<n>) holds one element per item, a lock and a frame; the station's
script only ever shows the element of a cell's current item, so VeilNet hides the ones it
has seen shown before each redraw (LOADOUTS). This writes the keys of every grid cell's
item and lock elements (not frames, not the three big boxes) as a sorted C array.

    python tools/station_icon_keys.py --canvas build/stage/59a9bd6e4525ecc4/72e4349798ae3ea1
"""
import argparse, os, re, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from le_symbol_names import symbol64  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--canvas", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "plugin", "station_icon_keys.h"))
    a = ap.parse_args()
    d = open(a.canvas, "rb").read()
    n = struct.unpack_from("<I", d, 0x1A0)[0]
    start = len(d) - n * 24
    slots = {int(symbol64(f"{t}_icon_{k}"), 16) for t in ("ability", "grenade", "weapon") for k in range(12)}
    frame = int(symbol64("frame"), 16)
    keys = sorted(k for k, s, e in (struct.unpack_from("<QQQ", d, start + i * 24) for i in range(n))
                  if s in slots and e != frame)
    lines = ",\n".join("    " + ", ".join(f"0x{k:016x}ull" for k in keys[i:i + 4]) for i in range(0, len(keys), 4))
    # plain gear element names (canvases without an index, e.g. the station's loadout bar):
    # kind 0 tac mod, 1 ordnance, 2 weapon
    gear = [("ABILITY", ("heal", "sensor", "shield", "wraith", "smoke", "buff", "point")),
            ("GRENADE", ("det", "stun", "arc", "burst", "loc", "dot", "drone")),
            ("WEAPON", ("assault", "blaster", "scout", "rocket", "magnum", "smg", "chain", "rifle", "medigun"))]
    plain = sorted((int(symbol64(f"{p}_{i}"), 16), k) for k, (p, items) in enumerate(gear) for i in items)
    plain_lines = ",\n".join(f"    {{0x{h:016x}ull, {k}}}" for h, k in plain)
    open(a.out, "w").write(
        "// Generated by tools/station_icon_keys.py: the equipment station's grid cells' item and lock\n"
        "// element keys (sorted). See that script.\n#pragma once\n#include <cstdint>\n"
        f"constexpr uint64_t kStationIconKeys[{len(keys)}] = {{\n{lines}}};\n"
        "// plain gear element names (sorted): {key, kind 0 tac mod / 1 ordnance / 2 weapon}\n"
        "struct GearElement { uint64_t key; int kind; };\n"
        f"constexpr GearElement kGearElements[{len(plain)}] = {{\n{plain_lines}}};\n")
    print(f"{a.out}: {len(keys)} keys")


if __name__ == "__main__":
    main()
